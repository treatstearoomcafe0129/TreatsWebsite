'use strict';
// Shared helpers for motion-match. No dependencies beyond Node and Playwright.
const fs = require('fs');
const path = require('path');
const { createRequire } = require('module');
const { pathToFileURL } = require('url');

function die(msg, code = 2) {
  process.stderr.write(`motion-match: ${msg}\n`);
  process.exit(code);
}

// --key value, --flag, and repeatable keys (listed in `multi`).
function parseArgs(argv, { multi = [], flags = [] } = {}) {
  const out = { _: [] };
  for (const k of multi) out[k] = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) { out._.push(a); continue; }
    const key = a.slice(2);
    if (flags.includes(key)) { out[key] = true; continue; }
    const val = argv[++i];
    if (val === undefined) die(`--${key} needs a value`);
    if (multi.includes(key)) out[key].push(val); else out[key] = val;
  }
  return out;
}

function num(v, name, { min = -Infinity, max = Infinity, def } = {}) {
  if (v === undefined) return def;
  const n = Number(v);
  if (!Number.isFinite(n) || n < min || n > max) die(`--${name} must be a number between ${min} and ${max}`);
  return n;
}

function loadPlaywright() {
  const tries = [
    () => require('playwright'),
    () => createRequire(path.join(process.cwd(), 'noop.js'))('playwright'),
  ];
  for (const t of tries) { try { return t(); } catch { /* next */ } }
  die('Playwright was not found. Install it in the project with:\n  npm i -D playwright && npx playwright install chromium');
}

async function launch() {
  const { chromium } = loadPlaywright();
  try { return await chromium.launch(); } catch (e) {
    for (const p of [process.env.MOTION_MATCH_CHROMIUM, '/opt/pw-browsers/chromium']) {
      if (p && fs.existsSync(p)) return chromium.launch({ executablePath: p });
    }
    die(`could not start Chromium (${String(e.message).split('\n')[0]}). Run: npx playwright install chromium`);
  }
}

// Accept http(s) URLs, file URLs, or a path to a local HTML file. Nothing else.
function toUrl(input) {
  if (!input) die('--url is required');
  if (/^https?:\/\//i.test(input)) return new URL(input).href;
  if (/^file:\/\//i.test(input)) return new URL(input).href;
  if (/^[a-z][a-z0-9+.-]*:/i.test(input)) die(`unsupported URL scheme in ${input}`);
  const p = path.resolve(input);
  if (!fs.existsSync(p)) die(`no such file: ${p}`);
  return pathToFileURL(p).href;
}

// Every file this tool writes goes through here: names are generated by us
// (never taken from a page) and must resolve inside the output folder.
function outPath(root, ...parts) {
  const base = path.resolve(root);
  const p = path.resolve(base, ...parts);
  if (p !== base && !p.startsWith(base + path.sep)) die(`refusing to write outside ${base}`);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  return p;
}

// Empty a folder of the frame files we generate, and only those.
function resetFrames(dir) {
  fs.mkdirSync(dir, { recursive: true });
  for (const f of fs.readdirSync(dir)) if (/^frame-\d{4}\.png$/.test(f)) fs.unlinkSync(path.join(dir, f));
}

function frameName(i) { return `frame-${String(i).padStart(4, '0')}.png`; }

function listFrames(dir) {
  const d = fs.existsSync(path.join(dir, 'frames')) ? path.join(dir, 'frames') : dir;
  if (!fs.existsSync(d)) die(`no frames folder at ${dir}`);
  const files = fs.readdirSync(d).filter((f) => /^frame-\d{4}\.png$/.test(f)).sort();
  if (!files.length) die(`no frame-NNNN.png files in ${d}`);
  return files.map((f) => path.join(d, f));
}

function readJson(p) { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return null; } }

module.exports = { die, parseArgs, num, launch, toUrl, outPath, resetFrames, frameName, listFrames, readJson };
